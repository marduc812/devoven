// Letter frequency scores (English) — higher frequency = higher score
const LETTER_FREQ: Record<string, number> = {
  e: 12.7, t: 9.1, a: 8.2, o: 7.5, i: 7.0, n: 6.7, s: 6.3, h: 6.1,
  r: 6.0, d: 4.3, l: 4.0, c: 2.8, u: 2.8, m: 2.4, w: 2.4, f: 2.2,
  g: 2.0, y: 2.0, p: 1.9, b: 1.5, v: 1.0, k: 0.8, j: 0.2, x: 0.2,
  q: 0.1, z: 0.1,
};

export interface WordleConstraints {
  greenPattern: string;    // 5-char pattern, '.' for unknown, letter for known position
  yellowLetters: string[]; // letters present but wrong position
  grayLetters: string[];   // letters not in word
}

export function parseConstraints(input: string): WordleConstraints {
  const lines = input.split('\n').map(l => l.trim()).filter(l => l);
  let greenPattern = '.....';
  const yellowLetters: string[] = [];
  const grayLetters: string[] = [];

  for (const line of lines) {
    const colonIdx = line.indexOf(':');
    if (colonIdx === -1) continue;
    const key = line.slice(0, colonIdx).trim().toLowerCase();
    const val = line.slice(colonIdx + 1).trim();

    if (key === 'green') {
      // Expected format: _A_LE or .A.LE (5 chars, '.' or '_' for unknown)
      const pattern = val.replace(/_/g, '.').toUpperCase();
      if (pattern.length === 5) {
        greenPattern = pattern;
      }
    } else if (key === 'yellow') {
      const letters = val.split(',').map(l => l.trim().toLowerCase()).filter(l => /^[a-z]$/.test(l));
      yellowLetters.push(...letters);
    } else if (key === 'gray') {
      const letters = val.split(',').map(l => l.trim().toLowerCase()).filter(l => /^[a-z]$/.test(l));
      grayLetters.push(...letters);
    }
  }

  return { greenPattern, yellowLetters, grayLetters };
}

export function filterWords(constraints: WordleConstraints, wordList: string[]): string[] {
  const { greenPattern, yellowLetters, grayLetters } = constraints;
  const graySet = new Set(grayLetters.map(l => l.toLowerCase()));
  const yellowSet = new Set(yellowLetters.map(l => l.toLowerCase()));
  const green = greenPattern.toLowerCase();

  return wordList.filter(word => {
    const w = word.toLowerCase();
    if (w.length !== 5) return false;

    // Check green positions
    for (let i = 0; i < 5; i++) {
      if (green[i] !== '.' && green[i] !== w[i]) return false;
    }

    // Check gray letters (must not be in word)
    for (const ch of graySet) {
      // Only exclude if not also in green/yellow (handles duplicate letter edge cases)
      if (!yellowSet.has(ch) && green.indexOf(ch) === -1) {
        if (w.includes(ch)) return false;
      }
    }

    // Check yellow letters (must be in word but not at green position)
    for (const ch of yellowSet) {
      if (!w.includes(ch)) return false;
    }

    return true;
  });
}

export function scoreWordFreq(word: string): number {
  let score = 0;
  const seen = new Set<string>();
  for (const ch of word.toLowerCase()) {
    if (!seen.has(ch)) {
      score += LETTER_FREQ[ch] || 0;
      seen.add(ch);
    }
  }
  return score;
}

export function formatWordleSolver(input: string): string {
  if (!input.trim()) return '';
  const constraints = parseConstraints(input);
  const filtered = filterWords(constraints, WORD_LIST);
  filtered.sort((a, b) => scoreWordFreq(b) - scoreWordFreq(a));

  const lines: string[] = [];
  lines.push(`Constraints parsed:`);
  lines.push(`  Green pattern:  ${constraints.greenPattern}`);
  lines.push(`  Yellow letters: ${constraints.yellowLetters.join(', ') || '(none)'}`);
  lines.push(`  Gray letters:   ${constraints.grayLetters.join(', ') || '(none)'}`);
  lines.push('');
  lines.push(`Possible words: ${filtered.length}`);
  if (filtered.length === 0) {
    lines.push('  No matches found. Check your constraints or try relaxing some.');
  } else {
    const show = Math.min(filtered.length, 30);
    lines.push(`Top ${show} suggestions (sorted by letter frequency score):`);
    for (let i = 0; i < show; i++) {
      const w = filtered[i];
      const score = scoreWordFreq(w).toFixed(1);
      lines.push(`  ${(i + 1).toString().padStart(2)}. ${w.toUpperCase()}  (score: ${score})`);
    }
    if (filtered.length > 30) {
      lines.push(`  ... and ${filtered.length - 30} more`);
    }
  }
  lines.push('');
  lines.push('How to use:');
  lines.push('  green: _A_LE    (known positions; use _ or . for unknowns)');
  lines.push('  yellow: T,R     (in word but wrong position, comma-separated)');
  lines.push('  gray: S,N,D     (not in word, comma-separated)');
  lines.push('');
  lines.push('Example input:');
  lines.push('  green: .A.LE');
  lines.push('  yellow: T');
  lines.push('  gray: S,N');
  return lines.join('\n');
}
